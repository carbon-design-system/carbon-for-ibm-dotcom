import { css } from 'lit';
import { customElement, property } from 'lit/decorators.js';
import settings from '@carbon/ibmdotcom-utilities/es/utilities/settings/settings.js';
import styles from './leadspace-with-search.scss';
import StableSelectorMixin from '../../globals/mixins/stable-selector';
import C4DContentBlockParagraph from '../content-block/content-block-paragraph';

const { stablePrefix: c4dPrefix } = settings;

/**
 * Copy in the content section of Leadspace with search
 *
 * @element c4d-leadspace-with-search-copy
 */
@customElement(`${c4dPrefix}-leadspace-with-search-copy`)
class C4DLeadspaceWithSearchCopy extends StableSelectorMixin(
  C4DContentBlockParagraph
) {
  /**
   * The shadow slot the content should be in.
   */
  @property({ reflect: true })
  slot = 'copy';

  connectedCallback() {
    this.setAttribute('slot', 'copy');
    super.connectedCallback();
  }

  static get stableSelector() {
    return `${c4dPrefix}--leadspace-with-search-content-copy`;
  }

  // `styles` here is a `CSSResult` generated by custom WebPack loader
  static get styles() {
    return css`
      ${super.styles}${styles}
    `;
  }
}

/* @__GENERATE_REACT_CUSTOM_ELEMENT_TYPE__ */
export default C4DLeadspaceWithSearchCopy;
